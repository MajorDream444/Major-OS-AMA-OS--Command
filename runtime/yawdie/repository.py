#!/usr/bin/env python3
"""Read-only, bounded snapshots of explicitly approved local repositories."""
import hashlib
import json
import os
import subprocess
import uuid
from pathlib import Path

from path_policy import PathPolicy, PathPolicyError, TemporarilyUnavailable

TEXT_SUFFIXES = ('.md', '.txt', '.json', '.toml', '.yaml', '.yml', '.py', '.js', '.ts', '.tsx', '.jsx', '.html', '.css')
MAX_FILES = 32
MAX_FILE_BYTES = 8192
MAX_TOTAL_BYTES = 32768


def _git(root, *args):
    result = subprocess.run(
        ['/usr/bin/git', '-C', str(root), *args], capture_output=True, text=True,
        timeout=10, env={'PATH': '/usr/bin:/bin', 'GIT_CONFIG_NOSYSTEM': '1'},
    )
    if result.returncode:
        raise PathPolicyError('approved root is not a readable Git checkout')
    return result.stdout.strip()


def load_manifest(path):
    manifest = Path(path).expanduser().resolve(strict=True)
    if manifest.is_symlink() or manifest.stat().st_mode & 0o077:
        raise PathPolicyError('repository manifest must be private and not a symlink')
    data = json.loads(manifest.read_text())
    repositories = data.get('repositories')
    if not isinstance(repositories, dict) or not repositories:
        raise PathPolicyError('manifest must contain approved repositories')
    return repositories


def snapshot(spec):
    root = Path(spec['root']).expanduser()
    includes = spec.get('include')
    if not isinstance(includes, list) or not includes:
        raise PathPolicyError('repository includes must be explicit')
    policy = PathPolicy(root, tuple(includes), suffixes=TEXT_SUFFIXES, max_file_bytes=MAX_FILE_BYTES)
    candidates = []
    for include in includes:
        try:
            _, target = policy.resolve(include, require_file=False)
            if target.is_file():
                candidates.append(str(include))
            elif target.is_dir():
                candidates.extend(policy.text_files(include, MAX_FILES - len(candidates)))
        except TemporarilyUnavailable:
            continue
        if len(candidates) >= MAX_FILES:
            break
    files, used, unavailable, rejected = [], 0, [], []
    for relative in dict.fromkeys(candidates):
        try:
            item = policy.read_text(relative)
        except TemporarilyUnavailable:
            unavailable.append(relative)
            continue
        except PathPolicyError:
            rejected.append(relative)
            continue
        remaining = MAX_TOTAL_BYTES - used
        if remaining <= 0:
            break
        encoded = item['text'].encode('utf-8')
        text = encoded[:remaining].decode('utf-8', errors='ignore')
        used += len(text.encode('utf-8'))
        files.append({key: item[key] for key in ('relative_path', 'sha256', 'bytes')} | {'text': text})
    head = _git(policy.root, 'rev-parse', 'HEAD')
    status = _git(policy.root, 'status', '--porcelain=v1', '--untracked-files=normal')
    digest_input = json.dumps({'head': head, 'dirty': bool(status), 'files': files}, sort_keys=True).encode()
    return {
        'commit': head, 'dirty': bool(status), 'dirty_entries': len(status.splitlines()) if status else 0,
        'files': files, 'bytes': used, 'unavailable': unavailable, 'rejected': rejected,
        'truncated': used >= MAX_TOTAL_BYTES or len(candidates) >= MAX_FILES,
        'snapshot_sha256': hashlib.sha256(digest_input).hexdigest(),
    }


def snapshot_named(manifest_path, names):
    configured = load_manifest(manifest_path)
    result = {}
    for name in names:
        if name not in configured:
            raise PathPolicyError('repository is not approved in the private manifest')
        result[name] = snapshot(configured[name])
    return result


def markdown(snapshots):
    lines = ['# Approved repository snapshot', '', 'Generated by the read-only Yawdie repository adapter.', '']
    for name, item in snapshots.items():
        lines += [f'## {name}', '', f"- Commit: `{item['commit']}`", f"- Dirty: `{str(item['dirty']).lower()}`",
                  f"- Dirty entries: `{item['dirty_entries']}`", f"- Snapshot SHA-256: `{item['snapshot_sha256']}`",
                  f"- Included bytes: `{item['bytes']}`", '']
        for file in item['files']:
            lines += [f"### `{file['relative_path']}`", '', f"SHA-256: `{file['sha256']}`", '', '```text', file['text'], '```', '']
        for path in item['unavailable']:
            lines.append(f'- Temporarily unavailable: `{path}`')
        for path in item['rejected']:
            lines.append(f'- Rejected by path policy: `{path}`')
    return '\n'.join(lines).rstrip() + '\n'


def context_markdown(snapshots, limit=3900):
    lines = ['# Approved repository snapshot', '', 'Read-only source evidence for bounded Yawdie drafting.', '']
    for name, item in snapshots.items():
        lines += [f'## {name}', f"- Commit: `{item['commit']}`", f"- Dirty: `{str(item['dirty']).lower()}`",
                  f"- Dirty entries: `{item['dirty_entries']}`", f"- Snapshot SHA-256: `{item['snapshot_sha256']}`"]
        for file in item['files']:
            excerpt = ' '.join(file['text'].split())[:320]
            lines += [f"- Source: `{file['relative_path']}` — `{file['sha256']}`", f'  - Excerpt: {excerpt}']
        for path in item['unavailable']:
            lines.append(f'- Temporarily unavailable: `{path}`')
        for path in item['rejected']:
            lines.append(f'- Rejected by path policy: `{path}`')
        lines.append('')
    content = '\n'.join(lines).rstrip() + '\n'
    encoded = content.encode('utf-8')
    if len(encoded) > limit:
        content = encoded[:limit - 20].decode('utf-8', errors='ignore').rstrip() + '\n\n[truncated]\n'
    return content


def export_context(vault_root, output_name, content):
    if not output_name.startswith('YAWDIE_REPOSITORY_SNAPSHOT_') or not output_name.endswith('.md'):
        raise PathPolicyError('generated context filename is not approved')
    policy = PathPolicy(vault_root, ('Yawdie/Context',), suffixes=('.md',), max_file_bytes=MAX_TOTAL_BYTES * 4)
    _, directory = policy.resolve('Yawdie/Context', require_file=False)
    destination = directory / output_name
    if destination.exists() or destination.is_symlink():
        raise FileExistsError('generated context is never overwritten')
    temporary = directory / ('.' + output_name + '.' + uuid.uuid4().hex + '.tmp')
    try:
        with temporary.open('x', encoding='utf-8') as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, destination)
    except OSError as exc:
        temporary.unlink(missing_ok=True)
        raise TemporarilyUnavailable('context output is temporarily unavailable') from exc
    return 'Yawdie/Context/' + output_name
